import { adapterSupportsModel, type AiProviderTemplate } from "../provider-templates";
import catalogJson from "./catalog.json";
import { normalizeModelId, type CatalogData, type CatalogModel } from "./types";
import { MODEL_VENDORS, findModelVendor } from "./vendors";

export { normalizeModelId, type CatalogModel } from "./types";

/** Catalog models shown together under a provider or vendor name. */
export interface CatalogGroup {
    name: string;
    models: CatalogModel[];
}

function newestFirst(a: CatalogModel, b: CatalogModel): number {
    return (b.releaseDate ?? "").localeCompare(a.releaseDate ?? "") || a.name.localeCompare(b.name);
}

/** A model can fill some role: generation models only serve image description. */
function isUsable(model: CatalogModel): boolean {
    return model.category !== "generation" || ("inputModalities" in model.capabilities && model.capabilities.inputModalities.includes("image"));
}

export function createModelCatalog(data: CatalogData) {
    function findInProvider(catalogProviderId: string | undefined, normalizedId: string): CatalogModel | null {
        if (!catalogProviderId) return null;
        return data.providers[catalogProviderId]?.find((model) => normalizeModelId(model.name) === normalizedId) ?? null;
    }

    /**
     * The definition of a model id as served by a provider created from `template`: the
     * provider's own listing first, then the provider a gateway namespace names (`deepseek/…`),
     * then the listing of the vendor that publishes the id.
     */
    function lookupModel(template: AiProviderTemplate, id: string): CatalogModel | null {
        const normalizedId = normalizeModelId(id);
        const namespace = id.trim().toLowerCase().split("/").at(-2);
        return (
            findInProvider(template.catalogProviderId, normalizedId) ??
            findInProvider(namespace, normalizedId) ??
            findInProvider(findModelVendor(normalizedId)?.catalogProviderId, normalizedId)
        );
    }

    return {
        /**
         * Catalog models to offer for a provider created from `template`, newest first. A provider
         * with its own listing offers that listing; gateways and self-hosted servers can serve any
         * vendor's models, so they get every vendor's own models grouped by vendor.
         */
        getProviderCatalog(template: AiProviderTemplate): CatalogGroup[] {
            const offered = (model: CatalogModel) => isUsable(model) && adapterSupportsModel(template.adapter, model.category, model.capabilities);
            if (template.catalogProviderId) {
                const models = (data.providers[template.catalogProviderId] ?? []).filter(offered).sort(newestFirst);
                return models.length > 0 ? [{ name: template.name, models }] : [];
            }
            return MODEL_VENDORS.map((vendor) => ({
                name: vendor.name,
                models: (data.providers[vendor.catalogProviderId] ?? [])
                    .filter((model) => offered(model) && findModelVendor(normalizeModelId(model.name)) === vendor)
                    .sort(newestFirst),
            })).filter((group) => group.models.length > 0);
        },

        /**
         * Known definitions for model ids a provider serves (typed by the user or listed by the
         * provider's API). Each match carries the id exactly as given; ids the provider's adapter
         * cannot serve are skipped. Text-only generation models are returned so callers can say
         * why they cannot describe images.
         */
        matchCatalogModels(template: AiProviderTemplate, ids: string[]): CatalogModel[] {
            return [...new Set(ids)].flatMap((id) => {
                const model = lookupModel(template, id);
                return model && adapterSupportsModel(template.adapter, model.category, model.capabilities) ? [{ ...model, name: id }] : [];
            });
        },
    };
}

/** Generated by `bun run generate:model-catalog`; see curated.ts. */
export const CATALOG_DATA = catalogJson as unknown as CatalogData;

export const { getProviderCatalog, matchCatalogModels } = createModelCatalog(CATALOG_DATA);
